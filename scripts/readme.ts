import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

/** Writes the README's results block from reports/*.json. With --check, fails if the README differs. */
const root = join(__dirname, "..");
const read = (p: string) => JSON.parse(readFileSync(join(root, p), "utf8"));
const dev = read("reports/dev.json");
const heldPath = "reports/heldout/first_run.json";
const held = existsSync(join(root, heldPath)) ? read(heldPath) : null;
const timing = existsSync(join(root, "reports/timing.json")) ? read("reports/timing.json") : null;

const eur = (c: number) => `€${Math.round(c / 100).toLocaleString("en-US")}`;
const of = (a: number, b: number) => `${a.toLocaleString("en-US")} of ${b.toLocaleString("en-US")}`;
const n = (a: number) => a.toLocaleString("en-US");

type Row = [string, (t: any) => string];
const rows: Row[] = [
  ["Commitments read from scanned subscription documents", (t) => of(t.commitments.right, t.commitments.checked)],
  ["Forms that needed a person, sent to one", (t) => of(t.documents.caught, t.documents.neededReview)],
  ["Forms accepted with a wrong field", (t) => n(t.documents.acceptedWrong)],
  ["Investor shares of every call, after all later closings", (t) => of(t.shares.right, t.shares.checked)],
  ["Equalisation per investor per closing (catch-up, credit, interest)", (t) => of(t.equalisation.right, t.equalisation.checked)],
  ["Notices with the right share, credit used and amount due", (t) => of(t.notices.right, t.notices.expected)],
  ["Notices that reached the investor exactly once", (t) => of(t.delivery.exactlyOnce, t.delivery.notices)],
  ["Investor payments settled by the rules (the rest by a person)", (t) => of(t.payments.autoRight, t.payments.investorEntries)],
  ["Payments tied to the wrong notice", (t) => n(t.payments.autoWrong)],
  ["Defaults declared that should have been", (t) => of(t.defaults.flagged, t.defaults.truth)],
  ["Defaults declared that should not have been", (t) => n(t.defaults.falseFlags)],
  ["Distribution waterfalls right tier by tier", (t) => of(t.waterfall.tiersRight, t.waterfall.distributions)],
  ["Investor shares of distributions", (t) => of(t.waterfall.sharesRight, t.waterfall.sharesChecked)],
  ["Duplicate concurrent requests that created a second event", (t) => `${n(t.idempotency.extraEvents)} (of ${n(t.idempotency.duplicateRequests)} sent)`],
  ["Requests for another manager's fund refused", (t) => of(t.tenancy.probesRefused, t.tenancy.probes)],
  ["Cash on the fund accounts not accounted for", (t) => eur(t.cash.unaccounted)],
];

const t = dev.total;
const h = held?.total;
const lines: string[] = [];
lines.push("<!-- results:start (generated by scripts/readme.ts from reports/; do not edit) -->");
lines.push("");
lines.push(`**Worlds:** ${n(t.funds)} development funds with ${n(t.investors)} investors, ${n(t.closings)} closings, ${n(t.calls)} capital calls and ${n(t.distributions)} distributions` +
  (h ? `; held-out: ${n(h.funds)} funds, ${n(h.investors)} investors, ${n(h.closings)} closings, ${n(h.calls)} calls, ${n(h.distributions)} distributions.` : "."));
lines.push("");
lines.push(`| Checked against the answer key | Development (seeds ${dev.seeds.join(", ")}) | Held-out (seeds ${held ? held.seeds.join(", ") : "–"}, run once) |`);
lines.push("|---|---:|---:|");
for (const [label, f] of rows) lines.push(`| ${label} | ${f(t)} | ${h ? f(h) : "not run"} |`);
lines.push("");
lines.push("**What the world threw at it (development):** " +
  `${n(t.faults.unavailable)} provider refusals, ${n(t.faults.ambiguousDelivered + t.faults.ambiguousLost)} timeouts (some after the provider had accepted), ` +
  `${n(t.faults.crashes)} process crashes between send and save, ${n(t.faults.statementResends)} bank statements delivered twice, ` +
  `${n(t.payments.noise)} credits that were nobody's payment, ${n(t.documents.neededReview)} subscription forms with a wrong IBAN, words that disagree with the figures, the wrong fund or no e-mail. ` +
  `Equalisation moved ${eur(t.equalisation.catchUp)} of catch-up and ${eur(t.equalisation.interest)} of interest between investors.`);
lines.push("");
lines.push("**Switch one safeguard off** (same development worlds):");
lines.push("");
lines.push("| Safeguard switched off | With it | Without it |");
lines.push("|---|---:|---:|");
const a = dev.ablations;
lines.push(`| Fall back to the payer's known IBAN when the reference is missing or mistyped | ${n(t.payments.toReview)} payments to a person | ${n(a.no_iban_fallback.payments.toReview)} payments to a person |`);
lines.push(`| Ask the provider before re-sending an unconfirmed notice | ${n(t.delivery.twiceOrMore)} notices sent twice | ${n(a.blind_retry.delivery.twiceOrMore)} notices sent twice |`);
if (timing) {
  const worst = (k: string) => Math.max(...timing.latencyMsP95.map((r: any) => r[k]));
  lines.push("");
  lines.push(`**Latency (p95, MySQL 8 on one machine, worst development seed):** closing with equalisation ${worst("closing")} ms, capital call ${worst("call")} ms, distribution ${worst("distribution")} ms, camt.053 statement ${worst("statement")} ms.`);
}
lines.push("");
lines.push("<!-- results:end -->");
const block = lines.join("\n");

const readmePath = join(root, "README.md");
const readme = readFileSync(readmePath, "utf8");
const next = readme.replace(/<!-- results:start[\s\S]*?<!-- results:end -->/, block);
if (process.argv.includes("--check")) {
  if (next !== readme) {
    console.error("README results block is out of date; run npx tsx scripts/readme.ts");
    process.exit(1);
  }
  console.error("README matches the reports");
} else {
  writeFileSync(readmePath, next);
  console.error("README updated");
}
